def test_a_larger_shop_keeps_the_per_customer_rates(load_job, tmp_path):
    rates = {}
    for customers in (500, 1000):
        root = tmp_path / str(customers)
        generate(load_job, root, "2026-05-18", P2_NUM_CUSTOMERS=str(customers))
        raw = root / "data" / "raw" / "batch_date=2026-05-18"
        people = pd.read_csv(raw / "customers.csv")
        events = (raw / "web_events.json").read_text(encoding="utf-8").splitlines()
        orders = pd.read_csv(raw / "orders.csv")
        truth = pd.read_json(raw / "generation_truth.json", lines=True)
        duplicate = truth[(truth["kind"] == "quality_fixture") & (truth["reason"] == "duplicate_customer")]
        assert int(people["user_id"].max()) == customers
        assert duplicate["row_index"].tolist() == [customers]
        assert people.loc[customers, "user_id"] == people.loc[3, "user_id"], "the duplicate is the 4th customer again"
        assert len(events) == 16 * customers + 1, "the web events of the anchor batch, and the dirty one"
        rates[customers] = len(orders) / customers
    assert rates[1000] == pytest.approx(rates[500], rel=0.10)


