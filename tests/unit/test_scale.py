# --- Typed DuckDB columns with NULLs: the same SQL type in every chunk ---------------

NULLABLE_DUCKDB_TYPES = {"c_int": "INTEGER", "c_bigint": "BIGINT", "c_bool": "BOOLEAN", "c_double": "DOUBLE",
                         "c_date": "DATE", "c_ts": "TIMESTAMP"}


def write_nullable_parquet(project_root: Path, layout: str, rows: int = 5000) -> Path:
    """Nullable typed columns. layout "late": no NULL in the first 2,048 rows (the first chunk), NULLs later;
    "early": only NULLs in the first 2,100 rows, values later."""
    import datetime as dt

    import pyarrow as pa
    import pyarrow.parquet as pq

    def is_null(index: int) -> bool:
        return index >= 2048 and index % 3 == 0 if layout == "late" else index < 2100

    def column(value, kind):
        return pa.array([None if is_null(index) else value(index) for index in range(rows)], type=kind)

    table = pa.table({
        "id": pa.array(range(rows), type=pa.int64()),
        "c_int": column(lambda index: index, pa.int32()),
        "c_bigint": column(lambda index: index * 1_000_003, pa.int64()),
        "c_bool": column(lambda index: index % 2 == 0, pa.bool_()),
        "c_double": column(lambda index: index / 7, pa.float64()),
        "c_date": column(lambda index: dt.date(2026, 5, 18) + dt.timedelta(days=index % 30), pa.date32()),
        "c_ts": column(lambda index: dt.datetime(2026, 5, 18) + dt.timedelta(minutes=index), pa.timestamp("us")),
    })
    folder = project_root / "gold" / "fact_web_events" / "gold_processed_date=2026-06-18"
    folder.mkdir(parents=True)
    pq.write_table(table, folder / "part-0.parquet")
    return project_root / "gold" / "fact_web_events" / "**" / "*.parquet"


def publish_three_ways(job, engine, glob: Path, schema_kwargs: dict) -> None:
    """pandas' own to_sql of the whole frame, the job in one chunk, and the job in chunks of 2,048 rows."""
    with engine.begin() as conn:
        job.prepare_dataframe_for_postgres(job.read_gold_table(glob)).to_sql(
            "pandas_whole", conn, index=False, method="multi", chunksize=1000, **schema_kwargs)
    sql_types = job.gold_table_sql_types(glob)
    assert job.publish_table(engine, "whole", job.read_gold_table_chunks(glob), sql_types) == 5000
    assert job.publish_table(engine, "chunked", job.read_gold_table_chunks(glob, chunk_rows=2048), sql_types) == 5000


@pytest.mark.parametrize("layout", ["late", "early"])
def test_typed_columns_with_nulls_get_the_same_sqlite_types_in_chunks(load_job, project_root, layout):
    import duckdb
    from sqlalchemy import create_engine, text

    job = load_job("sql/publish_gold_to_postgres.py")
    glob = write_nullable_parquet(project_root, layout)
    relation = duckdb.sql(job.gold_table_query(glob))
    assert {name: str(kind) for name, kind in zip(relation.columns, relation.types)
            if name in NULLABLE_DUCKDB_TYPES} == NULLABLE_DUCKDB_TYPES
    job.POSTGRES_SCHEMA = None   # SQLite has no schemas
    engine = create_engine("sqlite://")
    publish_three_ways(job, engine, glob, {})
    with engine.connect() as conn:
        assert sqlite_types(conn, "chunked") == sqlite_types(conn, "whole") == sqlite_types(conn, "pandas_whole")
