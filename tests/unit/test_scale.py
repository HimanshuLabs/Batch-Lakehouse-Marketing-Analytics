def raw_hashes(root: Path) -> dict[str, str]:
    raw = root / "data" / "raw"
    return {path.relative_to(raw).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(raw.glob("batch_date=*/*"))}


def hidden_folders(root: Path) -> list[str]:
    return sorted(path.name for path in (root / "data" / "raw").iterdir() if path.name.startswith("."))


def generate(load_job, root: Path, batch_date: str, **env: str):
    module = load_job(GENERATOR, root=root, BATCH_DATE=batch_date, **env)
    module.main()
    return module


